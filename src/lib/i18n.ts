const dict = { fa, en } as const;

export function t(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let text: string = dict[lang][key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replace(`{${name}}`, String(value));
    }
  }
  return text;
}

export function categoryLabel(lang: Lang, category: Category): string {
  return t(lang, `categories_${category}`);
}

export function weekdayShort(lang: Lang, weekday: number): string {
  return t(lang, `weekdayShort_${weekday}` as Key);
}

export function formatDate(lang: Lang, key: string): string {
  const [y, m, d] = key.split("-").map(Number);
  const date = new Date(y, m - 1, d);
  return new Intl.DateTimeFormat(lang === "fa" ? "fa-IR-u-ca-persian" : "en-US", {
    weekday: "long",
    day: "numeric",
    month: "long",
  }).format(date);
}
